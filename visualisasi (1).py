import io
import matplotlib.pyplot as plt
import pandas as pd
import requests

# 1. Ambil data
url = "https://raw.githubusercontent.com/Alam-A99/DATAAKSI/main/dataset_fiskal_97_hipoFull.csv"
res = requests.get(url, verify=False)
df = pd.read_csv(io.StringIO(res.text))

# 2. Kelompokkan data berdasarkan Kota dan ambil rata-rata DBH_PAJAK
# (Membuat setiap kota hanya muncul 1 batang)
df_grouped = (
    df.groupby('Kota')['DBH_PAJAK']
    .mean()
    .reset_index()
    .sort_values('DBH_PAJAK', ascending=False)
)

# Ambil 8 kota teratas saja agar grafiknya rapi & proporsional
df_pilihan = df_grouped.head(8)

# 3. Warna pastel
warna_pastel = [
    '#ffb3ba',
    '#ffdfba',
    '#ffffba',
    '#baffc9',
    '#bae1ff',
    '#e8baff',
    '#ffb3e6',
    '#c4faf8',
]

# 4. Plot grafik
plt.figure(figsize=(10, 5))

# Atur width=0.5 agar batangnya tidak terlalu lebar
plt.bar(
    df_pilihan['Kota'],
    df_pilihan['DBH_PAJAK'],
    color=warna_pastel[: len(df_pilihan)],
    edgecolor='#ff9ebb',
    linewidth=1.5,
    width=0.5,
)

plt.title(
    'Rata-Rata DBH PAJAK per Kota', fontsize=12, fontweight='bold', color='#d6336c'
)
plt.xlabel('Kota', fontsize=10, color='#c2255c')
plt.ylabel('DBH_PAJAK', fontsize=10, color='#c2255c')

plt.xticks(rotation=35, fontsize=9, ha='right')
plt.grid(axis='y', linestyle='--', alpha=0.5)

plt.tight_layout()
plt.show()